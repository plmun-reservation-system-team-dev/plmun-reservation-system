alter table public.users add column if not exists id_number text;
alter table public.users add column if not exists id_photo  text;

create table if not exists public.admin (
  admin_id        integer generated by default as identity primary key,
  auth_id         uuid unique,
  last_name       text not null,
  first_name      text not null,
  middle_initial  text,
  email           text not null unique,
  contact_number  text,
  department      text,
  created_at      text not null default to_char(now() at time zone 'Asia/Manila', 'YYYY-MM-DD HH24:MI:SS')
);

create table if not exists public.equipment_category (
  category_id     integer primary key,
  category_name   text not null unique,
  description     text
);

create table if not exists public.equipment (
  equipment_id        integer primary key,
  category_id         integer not null,
  equipment_name      text not null,
  description         text,
  image               text,
  quantity_available  integer not null default 0,
  condition_status    text not null default 'Good',
  availability_status text not null default 'Available'
);

create table if not exists public.reservation (
  reservation_id      integer primary key,
  user_id             integer not null,
  admin_id            integer,
  event_name          text not null,
  event_date          text not null,
  start_time          text not null,
  end_time            text not null,
  event_location      text not null,
  purpose             text,
  reservation_date    text not null,
  reservation_status  text not null default 'Pending',
  approval_remarks    text
);

create table if not exists public.reservation_item (
  reservation_item_id integer primary key,
  reservation_id      integer not null,
  equipment_id        integer not null,
