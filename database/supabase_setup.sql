-- =====================================================================================
-- PLMun Reservation & Borrowing  -  SUPABASE (online PostgreSQL) setup
--
-- HOW TO RUN: Supabase dashboard > SQL Editor > New query > paste this whole file > Run.
-- It is safe to run again later: it only creates what is missing and never deletes data.
--
-- Accounts (emails + passwords) live in Supabase's own "Authentication" system, which also sends and checks the
-- e-mail verification code. The tables below hold everything else (profiles, equipment, reservations ...).
-- Tables are locked (Row Level Security ON, no direct access): the website only talks to them through the
-- functions at the bottom, which check who is asking.
--
-- Dates and times are stored as plain text ('YYYY-MM-DD', 'HH:MM:SS', 'YYYY-MM-DD HH:MM:SS') on purpose: the website
-- already works with exactly those strings, so nothing can be shifted by a time-zone conversion.
-- =====================================================================================

-- ---------- tables ----------
create table if not exists public.users (
  user_id         integer generated by default as identity primary key,
  auth_id         uuid unique,                       -- link to the Supabase login (set automatically)
  last_name       text not null,
  first_name      text not null,
  middle_initial  text,
  email           text not null unique,
  user_type       text not null default 'Student',   -- Student / Faculty / Staff
  contact_number  text,
  department      text,
  course          text,
  year_level      text,
  account_status  text not null default 'Active',    -- Pending (waiting for the Property Office) / Active / Rejected / Suspended / Deactivated
  id_number       text,                              -- student / employee ID number given at sign-up
  id_photo        text,                              -- photo of the PLMun ID (a small compressed picture, stored as text)
  created_at      text not null default to_char(now() at time zone 'Asia/Manila', 'YYYY-MM-DD HH24:MI:SS')
);
