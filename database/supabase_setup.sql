);

create table if not exists public.review (
  review_id       integer primary key,
  user_id         integer not null,
  reservation_id  integer not null,
  equipment_id    integer not null,
  rating          integer not null check (rating between 1 and 5),
  comment         text,
  review_date     text not null,
  unique (reservation_id, equipment_id)
);

create table if not exists public.borrowing (
  borrowing_id             integer primary key,
  reservation_id           integer not null unique,
  released_by              integer,
  release_datetime         text not null,
  expected_return_datetime text not null,
  borrowing_status         text not null default 'Borrowed',
  dispatch_notes           text
);

create table if not exists public.borrowing_item (
  borrowing_item_id   integer primary key,
  borrowing_id        integer not null,
  reservation_item_id integer not null,
  quantity_released   integer not null default 1,
  dispatch_condition  text not null default 'Good',
  notes               text
);

create table if not exists public.return_record (
  return_id         integer primary key,
  borrowing_id      integer not null,
  received_by       integer,
  return_datetime   text not null,
  return_status     text not null default 'Complete',
  inspection_notes  text
);

create table if not exists public.return_item (
  return_item_id      integer primary key,
  return_id           integer not null,
  borrowing_item_id   integer not null,
  quantity_returned   integer not null default 0,
  condition_on_return text not null default 'Good',
  damage_notes        text,
  inspection_status   text not null default 'Pending'
);

create table if not exists public.penalty (
  penalty_id      integer primary key,
  borrowing_id    integer not null,
  return_item_id  integer,
  assessed_by     integer,
  penalty_type    text not null,
  amount          numeric(10,2) not null default 0,
  reason          text,
  penalty_status  text not null default 'Unpaid',
  assessed_at     text not null
);

