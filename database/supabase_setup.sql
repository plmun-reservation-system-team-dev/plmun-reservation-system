-- Is this e-mail already used by an account? (callable before signing in, so sign-up can say "already registered")
create or replace function public.email_registered(p_email text)
returns boolean language sql security definer set search_path = public, auth as $$
  select exists (select 1 from public.users where lower(email) = lower(trim(p_email)))
      or exists (select 1 from public.admin where lower(email) = lower(trim(p_email)))
      or exists (select 1 from auth.users   where lower(email) = lower(trim(p_email)));
$$;

-- Is this student / employee ID number already used by an account that was not rejected? (callable before signing in)
create or replace function public.id_number_registered(p_id text)
returns boolean language sql security definer set search_path = public as $$
  select exists (select 1 from public.users
                 where lower(trim(id_number)) = lower(trim(p_id)) and account_status <> 'Rejected');
$$;

-- Creates the profile row for a freshly verified account (data comes from the sign-up form, stored with the login).
-- New accounts start as 'Pending': the Property Office has to approve them before they can log in.
-- The ID photo is sent separately (it is too big for the login record) and is only accepted as a small image.
-- Admins are recognised by their e-mail being in the admin table.
drop function if exists public.ensure_profile();
create or replace function public.ensure_profile(p_id_photo text default null)
returns void language plpgsql security definer set search_path = public, auth as $$
declare em text := lower(auth.jwt() ->> 'email'); m jsonb; ut text; photo text;
begin
  if auth.uid() is null or em is null then return; end if;
  if exists (select 1 from public.admin where lower(email) = em) then
    update public.admin set auth_id = auth.uid() where lower(email) = em and auth_id is null;
    return;
  end if;
  photo := case when p_id_photo like 'data:image/%' and length(p_id_photo) <= 1500000 then p_id_photo end;
  if exists (select 1 from public.users where auth_id = auth.uid()) then
    if photo is not null then   -- the photo may arrive a moment after the profile row was made
      update public.users set id_photo = photo where auth_id = auth.uid() and id_photo is null;
    end if;
    return;
  end if;
  select raw_user_meta_data into m from auth.users where id = auth.uid();
  m := coalesce(m, '{}'::jsonb);
  ut := case when m ->> 'user_type' in ('Student', 'Faculty', 'Staff') then m ->> 'user_type' else 'Student' end;
  insert into public.users (auth_id, last_name, first_name, middle_initial, email, user_type, contact_number, department, course, year_level,
                            id_number, id_photo, account_status)
  values (auth.uid(),
          left(coalesce(nullif(trim(m ->> 'last_name'), ''), 'User'), 60),
          left(coalesce(nullif(trim(m ->> 'first_name'), ''), 'New'), 60),
          nullif(left(trim(coalesce(m ->> 'middle_initial', '')), 1), ''),
          em, ut,
          nullif(left(trim(coalesce(m ->> 'contact_number', '')), 20), ''),
          nullif(left(trim(coalesce(m ->> 'department', '')), 100), ''),
          case when ut = 'Student' then nullif(left(trim(coalesce(m ->> 'course', '')), 100), '') end,
          case when ut = 'Student' then nullif(left(trim(coalesce(m ->> 'year_level', '')), 20), '') end,
          nullif(left(trim(coalesce(m ->> 'id_number', '')), 30), ''),
          photo, 'Pending')
  on conflict do nothing;
end $$;

-- Admin only: the ID photo of one user (kept out of get_snapshot because pictures are big).
create or replace function public.get_id_photo(p_user_id int)
returns text language plpgsql stable security definer set search_path = public, auth as $$
begin
  if auth.uid() is null or not exists (select 1 from public.admin where lower(email) = lower(auth.jwt() ->> 'email')) then
    raise exception 'Admin access only.' using errcode = '42501';
  end if;
  return (select id_photo from public.users where user_id = p_user_id);
end $$;

-- Everything the signed-in person is allowed to see, in one go. Admins see all; others see their own private data
-- and only the non-private parts of everyone else's (needed to work out what equipment is free).
create or replace function public.get_snapshot()
returns jsonb language plpgsql stable security definer set search_path = public, auth as $$
declare em text := lower(auth.jwt() ->> 'email'); aid int; uid int;
begin
  if auth.uid() is null then raise exception 'Please log in first.' using errcode = '28000'; end if;
  select admin_id into aid from public.admin where lower(email) = em;
  select user_id  into uid from public.users where auth_id = auth.uid();

  if aid is not null then
    return jsonb_build_object(
      'me', jsonb_build_object('role', 'admin', 'id', aid),
      'admin', (select coalesce(jsonb_agg(to_jsonb(x) - 'auth_id' order by admin_id), '[]') from public.admin x),
      'users', (select coalesce(jsonb_agg(to_jsonb(x) - 'auth_id' - 'id_photo' || jsonb_build_object('has_id_photo', x.id_photo is not null) order by user_id), '[]') from public.users x),
      'cat',   (select coalesce(jsonb_agg(to_jsonb(x) order by category_id), '[]') from public.equipment_category x),
      'eq',    (select coalesce(jsonb_agg(to_jsonb(x) order by equipment_id), '[]') from public.equipment x),
      'res',   (select coalesce(jsonb_agg(to_jsonb(x) order by reservation_id), '[]') from public.reservation x),
      'ri',    (select coalesce(jsonb_agg(to_jsonb(x) order by reservation_item_id), '[]') from public.reservation_item x),
      'rev',   (select coalesce(jsonb_agg(to_jsonb(x) order by review_id), '[]') from public.review x),
      'bor',   (select coalesce(jsonb_agg(to_jsonb(x) order by borrowing_id), '[]') from public.borrowing x),
      'bi',    (select coalesce(jsonb_agg(to_jsonb(x) order by borrowing_item_id), '[]') from public.borrowing_item x),
      'ret',   (select coalesce(jsonb_agg(to_jsonb(x) order by return_id), '[]') from public.return_record x),
      'rit',   (select coalesce(jsonb_agg(to_jsonb(x) order by return_item_id), '[]') from public.return_item x),
      'pen',   (select coalesce(jsonb_agg(to_jsonb(x) order by penalty_id), '[]') from public.penalty x));
  end if;

  return jsonb_build_object(
    'me', jsonb_build_object('role', 'user', 'id', uid),
    'admin', '[]'::jsonb,
    'users', (select coalesce(jsonb_agg(
               case when x.user_id = uid then to_jsonb(x) - 'auth_id' - 'id_photo'
                    else jsonb_build_object('user_id', x.user_id, 'last_name', x.last_name, 'first_name', x.first_name,
                                            'middle_initial', x.middle_initial, 'user_type', x.user_type, 'email', '',
                                            'account_status', x.account_status) end
               order by x.user_id), '[]') from public.users x),
    'cat',   (select coalesce(jsonb_agg(to_jsonb(x) order by category_id), '[]') from public.equipment_category x),
    'eq',    (select coalesce(jsonb_agg(to_jsonb(x) order by equipment_id), '[]') from public.equipment x),
    'res',   (select coalesce(jsonb_agg(
               case when x.user_id = uid then to_jsonb(x)
                    else jsonb_build_object('reservation_id', x.reservation_id, 'user_id', x.user_id, 'event_name', x.event_name,
                                            'event_date', x.event_date, 'start_time', x.start_time, 'end_time', x.end_time,
                                            'reservation_date', x.reservation_date, 'reservation_status', x.reservation_status,
                                            'event_location', '') end
               order by x.reservation_id), '[]') from public.reservation x),
    'ri',    (select coalesce(jsonb_agg(to_jsonb(x) order by reservation_item_id), '[]') from public.reservation_item x),
    'rev',   (select coalesce(jsonb_agg(to_jsonb(x) order by review_id), '[]') from public.review x),
    'bor',   (select coalesce(jsonb_agg(
               case when exists (select 1 from public.reservation r where r.reservation_id = x.reservation_id and r.user_id = uid)
                    then to_jsonb(x) else to_jsonb(x) - 'dispatch_notes' end
               order by x.borrowing_id), '[]') from public.borrowing x),
    'bi',    (select coalesce(jsonb_agg(to_jsonb(x) - 'notes' order by borrowing_item_id), '[]') from public.borrowing_item x),
    'ret',   '[]'::jsonb,
    'rit',   (select coalesce(jsonb_agg(to_jsonb(x) - 'damage_notes' order by return_item_id), '[]') from public.return_item x),
    'pen',   (select coalesce(jsonb_agg(to_jsonb(p) order by p.penalty_id), '[]')
              from public.penalty p
              join public.borrowing b on b.borrowing_id = p.borrowing_id
              join public.reservation r on r.reservation_id = b.reservation_id
              where r.user_id = uid));
end $$;

-- Saves what the website changed: { table: { inserts: [rows], updates: [{pk, changed fields}], deletes: [ids] } }.
-- Admins may change anything. Everybody else may only: add their own PENDING reservations (and their items), add their
-- own reviews, and cancel their own Pending/Approved reservations. Other changes from them are ignored.
create or replace function public.apply_changes(changes jsonb)
returns void language plpgsql security definer set search_path = public, auth as $$
declare
  em text := lower(auth.jwt() ->> 'email'); is_admin boolean; uid int;
  tbls text[] := array['equipment_category','equipment','users','admin','reservation','reservation_item','review',
                       'borrowing','borrowing_item','return_record','return_item','penalty'];
  pks jsonb := '{"equipment_category":"category_id","equipment":"equipment_id","users":"user_id","admin":"admin_id",
                 "reservation":"reservation_id","reservation_item":"reservation_item_id","review":"review_id",
                 "borrowing":"borrowing_id","borrowing_item":"borrowing_item_id","return_record":"return_id",
                 "return_item":"return_item_id","penalty":"penalty_id"}';
  t text; pk text; ch jsonb; r jsonb; sets text; cols text; pkv text; old_status text;
begin
  if auth.uid() is null then raise exception 'Please log in first.' using errcode = '28000'; end if;
  select exists (select 1 from public.admin where lower(email) = em) into is_admin;
  select user_id into uid from public.users where auth_id = auth.uid();
  -- an account that has not been approved yet (or was rejected / suspended) may not save anything
  if not is_admin and not exists (select 1 from public.users where auth_id = auth.uid() and account_status = 'Active') then
    raise exception 'Your account is not active.' using errcode = '42501';
  end if;

  -- inserts, parents first
  foreach t in array tbls loop
    ch := changes -> t; continue when ch is null;
    pk := pks ->> t;
    for r in select * from jsonb_array_elements(coalesce(ch -> 'inserts', '[]')) loop
      if not is_admin then
        continue when t not in ('reservation', 'reservation_item', 'review');
        if uid is null then raise exception 'Your profile is not ready yet.'; end if;
        if t = 'reservation' and not ((r ->> 'user_id')::int = uid and r ->> 'reservation_status' = 'Pending') then
          raise exception 'Not allowed.'; end if;
        if t = 'reservation_item' and not exists (select 1 from public.reservation x
              where x.reservation_id = (r ->> 'reservation_id')::int and x.user_id = uid and x.reservation_status = 'Pending') then
          raise exception 'Not allowed.'; end if;
        if t = 'review' and not ((r ->> 'user_id')::int = uid and exists (select 1 from public.reservation x
              where x.reservation_id = (r ->> 'reservation_id')::int and x.user_id = uid and x.reservation_status in ('Borrowed', 'Completed'))) then
          raise exception 'Not allowed.'; end if;
      end if;
      select string_agg(format('%I', k), ', ') into cols
        from jsonb_object_keys(r) k
        where k <> 'auth_id'
          and exists (select 1 from information_schema.columns c where c.table_schema = 'public' and c.table_name = t and c.column_name = k);
      execute format('insert into public.%I (%s) select %s from jsonb_populate_record(null::public.%I, $1)', t, cols, cols, t) using r;
    end loop;
  end loop;

  -- updates (only the fields that changed)
  foreach t in array tbls loop
    ch := changes -> t; continue when ch is null;
    pk := pks ->> t;
    for r in select * from jsonb_array_elements(coalesce(ch -> 'updates', '[]')) loop
      pkv := r ->> pk;
      if not is_admin then
        continue when t <> 'reservation';
        select reservation_status into old_status from public.reservation
          where reservation_id = pkv::int and user_id = uid;
        if old_status is null then raise exception 'Not allowed.'; end if;
        if not (r ->> 'reservation_status' = 'Cancelled' and old_status in ('Pending', 'Approved')
                and (select count(*) from jsonb_object_keys(r)) = 2) then
          raise exception 'Not allowed.'; end if;
      end if;
      select string_agg(format('%I = s.%I', k, k), ', ') into sets
        from jsonb_object_keys(r) k
        where k <> pk and k <> 'auth_id'
          and exists (select 1 from information_schema.columns c where c.table_schema = 'public' and c.table_name = t and c.column_name = k);
      continue when sets is null;
      execute format('update public.%I x set %s from (select * from jsonb_populate_record(null::public.%I, $1)) s where x.%I::text = $2', t, sets, t, pk)
        using r, pkv;
    end loop;
  end loop;

  -- deletes, children first (admins only)
  if is_admin then
    for i in reverse array_length(tbls, 1) .. 1 loop
      t := tbls[i]; ch := changes -> t; continue when ch is null;
      pk := pks ->> t;
      for r in select * from jsonb_array_elements(coalesce(ch -> 'deletes', '[]')) loop
        if t = 'users' then   -- free the login too, so the person can sign up again (unless this account just became an admin)
          delete from auth.users au
            where au.id = (select auth_id from public.users where user_id = (r #>> '{}')::int)
              and not exists (select 1 from public.admin a where lower(a.email) = lower(au.email));
        end if;
        execute format('delete from public.%I where %I::text = $1', t, pk) using (r #>> '{}');
      end loop;
    end loop;
  end if;
end $$;

